def synthetic(key="M2", days=10, seed=1, kappa_after=None, **p):
    """Inputs with a daily pattern, and temperatures generated by a known model."""
    rng = np.random.default_rng(seed)
    n = 288 * days
    t = np.arange(n) / 12
    occ = ((t % 24 > 8) & (t % 24 < 18)).astype(float)
    U = np.c_[30 + 3 * np.sin(2 * np.pi * (t - 9) / 24),
              occ * np.clip(2 + 0.5 * rng.standard_normal(n), 0, None),
              occ * 1.5 + 0.3,
              np.clip(np.sin(2 * np.pi * (t - 6) / 24), 0, None) * 0.8,
              np.ones(n)]
    m = RCModel(key)
    m.p.update(p)
    Ad, Bd, Qd, r = m.matrices()
    x = np.full(Ad.shape[0], 27.0)
    Y = np.empty(n)
    for k in range(n):
        Y[k] = x[0] + np.sqrt(r) * rng.standard_normal()
        u = U[k].copy()
        if kappa_after is not None and k >= n // 2:
            u[1] *= kappa_after
        x = Ad @ x + Bd @ u + rng.multivariate_normal(np.zeros(len(x)), Qd)
    return m, U, Y


TRUE_M2 = dict(Ci=0.4, Cm=8.0, Rio=0.6, Rim=0.08, a_int=0.9, a_sol=3.0, q0=0.2, q_Ti=0.02, q_Tm=0.002, r=0.005)


def test_discretisation_matches_fine_euler():
    m = RCModel("M3")
    A, B = continuous(m.spec, m.p)
    Ad, Bd = discretise(A, B, m.dt)
    x, u = np.array([25.0, 26.0, 28.0]), np.array([32.0, 2.0, 1.0, 0.5, 1.0])
    xe, h = x.copy(), m.dt / 20000
    for _ in range(20000):
        xe = xe + h * (A @ xe + B @ u)
    assert np.allclose(Ad @ x + Bd @ u, xe, atol=1e-3)


@pytest.mark.parametrize("key", ["M1", "M2", "M3"])
def test_scale_invariance(key):
    """Only ratios are identifiable: scaling capacities, gains and cooling by k (resistances by 1/k)
    leaves the dynamics unchanged. This is why the apparent COP is fixed (ETA_REF)."""
    spec = SPECS[key]
    p = dict(spec.guess, eta=ETA_REF)
    k = 2.7
    q = {n: v * k if n[0] in "Caq" or n == "eta" else v / k if n[0] == "R" else v for n, v in p.items()
         if not n.startswith("q_") and n != "r"}
    A1, B1 = continuous(spec, p)
    A2, B2 = continuous(spec, q)
    assert np.allclose(A1, A2) and np.allclose(B1, B2)


def test_identification_recovers_known_model():
    m, U, Y = synthetic(days=14, **TRUE_M2)
    Y[500:560] = np.nan                               # a sensor gap
    fit = RCModel("M2").fit(U, Y, starts=2)
    true_tau = sorted(m.time_constants_h())
    assert np.allclose(sorted(fit.time_constants_h()), true_tau, rtol=0.25)
    assert fit.p["Ci"] == pytest.approx(TRUE_M2["Ci"], rel=0.3)
    # the likelihood of the fit is at least that of the true parameters
    assert -fit.nll >= m.loglik(U, Y) - 1e-6


def test_model_selection_prefers_true_order():
    m, U, Y = synthetic(days=10, **TRUE_M2)
    aic = {k: RCModel(k).fit(U, Y, starts=1).aic for k in ("M1", "M2")}
    assert aic["M2"] < aic["M1"]


def test_kalman_innovations_are_white_and_unit_variance():
    m, U, Y = synthetic(days=10, **TRUE_M2)
    Ad, Bd, Qd, r = m.matrices()
    res = KalmanFilter(Ad, Bd, [1, 0], Qd, r, [27, 27], np.eye(2)).run(U, Y)
    z = res.normalised_innov[100:]
    assert 0.85 < np.var(z) < 1.15
    assert abs(np.corrcoef(z[:-1], z[1:])[0, 1]) < 0.1


def test_twin_without_tracking_equals_kalman_filter():
    m, U, Y = synthetic(days=3, **TRUE_M2)
    Ad, Bd, Qd, r = m.matrices()
    res = KalmanFilter(Ad, Bd, [1, 0], Qd, r, [Y[0], Y[0]], np.eye(2)).run(U, Y)
    o = DigitalTwin(m, Y[0], track=False).run(U, Y)
    assert np.allclose(o["innov"][1:], res.innov[1:], atol=1e-9, equal_nan=True)


def test_twin_tracks_loss_of_cooling():
    m, U, Y = synthetic(days=20, kappa_after=0.7, **TRUE_M2)
    o = DigitalTwin(m, Y[0], q_kappa=1e-5, q_dq=0.002).run(U, Y)
    on = U[:, 1] > 0.5
    late = np.arange(len(Y)) > len(Y) * 0.8
    early = (np.arange(len(Y)) < len(Y) * 0.45) & (np.arange(len(Y)) > 288)
    assert np.mean(o["kappa"][late & on]) == pytest.approx(0.7, abs=0.1)
    assert np.mean(o["kappa"][early & on]) == pytest.approx(1.0, abs=0.1)


def test_forecast_uncertainty_grows_with_horizon():
    m, U, Y = synthetic(days=2, **TRUE_M2)
    tw = DigitalTwin(m, Y[0])
    tw.run(U[:288], Y[:288])
    _, sd = tw.forecast(U[288:288 + 72])
    assert np.all(np.diff(sd) > -1e-9) and sd[-1] > sd[0]


def test_cusum_detects_bias_but_not_noise():
    rng = np.random.default_rng(0)
    z = rng.standard_normal(5000)
    assert len(dg.cusum(z, threshold=15)[0]) == 0
    z[3000:] += 2.0
    al = dg.cusum(z, threshold=15)[0]
    assert al and 3000 <= al[0] < 3020


def test_frozen_sensor_rule():
    y = np.r_[np.linspace(20, 25, 50), np.full(20, 25.0), np.linspace(25, 22, 30)]
    assert dg.frozen(y, steps=12) == [50 + 10]


def test_spike_filter_keeps_steps():
    x = pd.Series(np.r_[np.full(10, 30.0), np.full(10, 24.0)])        # AC switching on: a real step
    x2, n = D.spikes(x)
    assert n == 0 and x2.notna().all()
    x[5] = 35.0                                                         # a one-sample spike
    x3, n = D.spikes(x)
    assert n == 1 and np.isnan(x3[5])


def test_frozen_flags_whole_run():
    x = pd.Series(np.r_[np.arange(5.0), np.full(30, 7.0), np.arange(5.0)])
    f = D.frozen(x, min_steps=24)
    assert f.sum() == 30
